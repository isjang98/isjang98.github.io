#!/usr/bin/env python3
"""Render the English landing page from the Korean HTML and its data-en fields."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Final
from urllib.parse import urljoin, urlsplit

from bs4 import BeautifulSoup, Tag
from pydantic import JsonValue, TypeAdapter

ROOT: Final = Path(__file__).resolve().parents[1]
JSON_OBJECT: Final[TypeAdapter[dict[str, JsonValue]]] = TypeAdapter(dict[str, JsonValue])


class MissingPageElement(RuntimeError):
    """The authored page no longer provides a required build input."""

    def __init__(self, selector: str) -> None:
        self.selector: str = selector
        super().__init__(f"Required page element is missing: {selector}")


def required(parent: Tag, selector: str) -> Tag:
    element = parent.select_one(selector)
    if element is None:
        raise MissingPageElement(selector)
    return element


def render_english(source: str) -> str:
    """Translate at build time so crawlers and browsers receive the same HTML."""
    page = BeautifulSoup(source, "html.parser")
    root_url = str(required(page, 'link[rel="canonical"]')["href"])
    english_url = urljoin(root_url, "en/")
    required(page, "html")["lang"] = "en"

    for element in page.select("[data-ko-only]"):
        element.decompose()
    for element in page.select("[data-en-only]"):
        _ = element.attrs.pop("hidden", None)
    for element in page.select("[data-en]"):
        fragment = BeautifulSoup(str(element["data-en"]), "html.parser")
        element.clear()
        _ = element.extend(list(fragment.contents))

    for element in page.select("*"):
        for name in list(element.attrs):
            if name.startswith("data-en-") and name != "data-en-only":
                attribute = name.removeprefix("data-en-")
                if attribute == "label":
                    attribute = "aria-label"
                element[attribute] = element[name]
        for name in list(element.attrs):
            if name == "data-en" or name.startswith("data-en-"):
                del element[name]

    title = required(page, "title").get_text()
    description = str(required(page, 'meta[name="description"]')["content"])
    required(page, 'link[rel="canonical"]')["href"] = english_url
    for selector, content in {
        'meta[property="og:title"]': title,
        'meta[name="twitter:title"]': title,
        'meta[property="og:description"]': description,
        'meta[name="twitter:description"]': description,
        'meta[property="og:image:alt"]': title,
        'meta[name="twitter:image:alt"]': title,
        'meta[property="og:url"]': english_url,
    }.items():
        required(page, selector)["content"] = content

    for link in page.select(".cta-button"):
        store = (
            "Google Play"
            if "cta-button--android" in link.get_attribute_list("class")
            else "the App Store"
        )
        link["aria-label"] = f"Download BibleOn on {store}"

    app_script = required(page, "#app-schema")
    app = JSON_OBJECT.validate_json(app_script.get_text())
    app.update({
        "name": "BibleOn",
        "alternateName": "말씀온",
        "description": description,
        "url": english_url,
        "image": urljoin(root_url, "images/en/app-icon.png"),
        "screenshot": urljoin(root_url, "images/en/01-hero.webp"),
    })
    app_script.string = json.dumps(app, ensure_ascii=False, indent=2)

    faq_script = required(page, "#faq-schema")
    faq = JSON_OBJECT.validate_json(faq_script.get_text())
    faq.update({
        "@id": english_url + "#faq",
        "inLanguage": "en",
        "mainEntity": [{
            "@type": "Question",
            "name": " ".join(required(detail, "summary").get_text().split()),
            "acceptedAnswer": {
                "@type": "Answer",
                "text": " ".join(required(detail, "p").get_text().split()),
            },
        } for detail in page.select("#faq details")],
    })
    faq_script.string = json.dumps(faq, ensure_ascii=False, indent=2)

    # Only page-relative assets move one directory deeper; anchors stay local.
    for element in page.select("[src], [href], [poster]"):
        for name in ("src", "href", "poster"):
            if name not in element.attrs:
                continue
            reference = str(element[name])
            if (
                urlsplit(reference).path == "language.js"
                or reference.startswith(("images/", "videos/", "mov/"))
            ):
                element[name] = "../" + reference

    return str(page).replace(
        "<!DOCTYPE html>",
        "<!DOCTYPE html>\n<!-- Generated by tools/build_en.py; edit index.html and rebuild. -->",
        1,
    )


def main() -> int:
    if sys.argv[1:] not in ([], ["--check"]):
        print("Usage: python tools/build_en.py [--check]", file=sys.stderr)
        return 2

    generated = render_english((ROOT / "index.html").read_text(encoding="utf-8"))
    target = ROOT / "en" / "index.html"
    if "--check" in sys.argv[1:]:
        if not target.is_file() or target.read_text(encoding="utf-8") != generated:
            print("English HTML is stale; run python tools/build_en.py.", file=sys.stderr)
            return 1
        print("English HTML is synchronized.")
        return 0

    target.parent.mkdir(exist_ok=True)
    _ = target.write_text(generated, encoding="utf-8")
    print(f"Generated {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
